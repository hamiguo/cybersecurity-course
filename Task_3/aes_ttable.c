/* xtime 和 mul */
static uint8_t xtime(uint8_t a) { return (a<<1) ^ ((a&0x80)?0x1b:0); }
static uint8_t mul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    while (b) { if (b & 1) r ^= a; a = xtime(a); b >>= 1; }
    return r;
}

/* T‑table 和逆 T‑table */
static uint32_t T0[256], T1[256], T2[256], T3[256];
static uint32_t iT0[256], iT1[256], iT2[256], iT3[256];
static int tables_ready = 0;

static void prepare_tables(void) {
    if (tables_ready) return;
    for (int i = 0; i < 256; i++) {
        uint8_t s = sbox[i];
        uint8_t s2 = xtime(s);
        uint8_t s3 = s ^ s2;
        T0[i] = (s2 << 24) | (s  << 16) | (s  << 8) | s3;
        T1[i] = (s3 << 24) | (s2 << 16) | (s  << 8) | s;
        T2[i] = (s  << 24) | (s3 << 16) | (s2 << 8) | s;
        T3[i] = (s  << 24) | (s  << 16) | (s3 << 8) | s2;
    }
    for (int i = 0; i < 256; i++) {
        uint8_t s = inv_sbox[i];
        uint8_t s2 = xtime(s);
        uint8_t s4 = xtime(s2);
        uint8_t s8 = xtime(s4);
        uint8_t s9  = s8 ^ s;
        uint8_t s11 = s8 ^ s2 ^ s;
        uint8_t s13 = s8 ^ s4 ^ s;
        uint8_t s14 = s8 ^ s4 ^ s2;
        iT0[i] = (s14 << 24) | (s11 << 16) | (s13 << 8) | s9;
        iT1[i] = (s9  << 24) | (s14 << 16) | (s11 << 8) | s13;
        iT2[i] = (s13 << 24) | (s9  << 16) | (s14 << 8) | s11;
        iT3[i] = (s11 << 24) | (s13 << 16) | (s9  << 8) | s14;
    }
    tables_ready = 1;
}

/* 上下文（只保留加密轮密钥，解密复用加密轮密钥） */
typedef struct {
    uint32_t rk_enc[44];
} aes_ttable_ctx;

static const uint32_t Rcon[10] = {
    0x01000000, 0x02000000, 0x04000000, 0x08000000,
    0x10000000, 0x20000000, 0x40000000, 0x80000000,
    0x1b000000, 0x36000000
};

static void aes_ttable_key_schedule(const uint8_t *key, void *ctx) {
    prepare_tables();
    aes_ttable_ctx *c = (aes_ttable_ctx*)ctx;
    uint32_t *rke = c->rk_enc;
    for (int i = 0; i < 4; i++) rke[i] = GETU32(key + 4*i);
    for (int i = 4; i < 44; i++) {
        uint32_t t = rke[i-1];
        if (i % 4 == 0) {
            t = (sbox[(t >> 16) & 0xFF] << 24) |
                (sbox[(t >>  8) & 0xFF] << 16) |
                (sbox[ t        & 0xFF] <<  8) |
                (sbox[ t >> 24 ]);
            t ^= Rcon[i/4 - 1];
        }
        rke[i] = rke[i-4] ^ t;
    }
}

/* ========== 标量解密辅助（复用 basic 逻辑）========== */
static void AddRoundKey(uint8_t state[16], const uint32_t *rk) {
    for (int col = 0; col < 4; col++) {
        uint32_t w = rk[col];
        state[4*col+0] ^= (w >> 24) & 0xFF;
        state[4*col+1] ^= (w >> 16) & 0xFF;
        state[4*col+2] ^= (w >>  8) & 0xFF;
        state[4*col+3] ^= w & 0xFF;
    }
}
static void InvSubBytes(uint8_t state[16]) {
    for (int i = 0; i < 16; i++) state[i] = inv_sbox[state[i]];
}
static void InvShiftRows(uint8_t state[16]) {
    uint8_t tmp[16];
    tmp[0] = state[0];  tmp[1] = state[13]; tmp[2] = state[10]; tmp[3] = state[7];
    tmp[4] = state[4];  tmp[5] = state[1];  tmp[6] = state[14]; tmp[7] = state[11];
    tmp[8] = state[8];  tmp[9] = state[5];  tmp[10]= state[2];  tmp[11]= state[15];
    tmp[12]= state[12]; tmp[13]= state[9];  tmp[14]= state[6];  tmp[15]= state[3];
    memcpy(state, tmp, 16);
}
static void InvMixColumns(uint8_t state[16]) {
    for (int c = 0; c < 4; c++) {
        int idx = 4 * c;
        uint8_t a0 = state[idx+0], a1 = state[idx+1], a2 = state[idx+2], a3 = state[idx+3];
        state[idx+0] = mul(0x0e, a0) ^ mul(0x0b, a1) ^ mul(0x0d, a2) ^ mul(0x09, a3);
        state[idx+1] = mul(0x09, a0) ^ mul(0x0e, a1) ^ mul(0x0b, a2) ^ mul(0x0d, a3);
        state[idx+2] = mul(0x0d, a0) ^ mul(0x09, a1) ^ mul(0x0e, a2) ^ mul(0x0b, a3);
        state[idx+3] = mul(0x0b, a0) ^ mul(0x0d, a1) ^ mul(0x09, a2) ^ mul(0x0e, a3);
    }
}

/* ========== 加密（T‑table 优化）========== */
static void aes_ttable_encrypt(const uint8_t *in, uint8_t *out, const void *ctx) {
    const aes_ttable_ctx *c = (const aes_ttable_ctx*)ctx;
    const uint32_t *rk = c->rk_enc;
    uint32_t s0 = GETU32(in)     ^ rk[0];
    uint32_t s1 = GETU32(in+4)   ^ rk[1];
    uint32_t s2 = GETU32(in+8)   ^ rk[2];
    uint32_t s3 = GETU32(in+12)  ^ rk[3];
    for (int r = 1; r < 10; r++) {
        uint32_t t0 = T0[s0 >> 24] ^ T1[(s1 >> 16) & 0xFF] ^ T2[(s2 >> 8) & 0xFF] ^ T3[s3 & 0xFF] ^ rk[4*r];
        uint32_t t1 = T0[s1 >> 24] ^ T1[(s2 >> 16) & 0xFF] ^ T2[(s3 >> 8) & 0xFF] ^ T3[s0 & 0xFF] ^ rk[4*r+1];
        uint32_t t2 = T0[s2 >> 24] ^ T1[(s3 >> 16) & 0xFF] ^ T2[(s0 >> 8) & 0xFF] ^ T3[s1 & 0xFF] ^ rk[4*r+2];
        uint32_t t3 = T0[s3 >> 24] ^ T1[(s0 >> 16) & 0xFF] ^ T2[(s1 >> 8) & 0xFF] ^ T3[s2 & 0xFF] ^ rk[4*r+3];
        s0 = t0; s1 = t1; s2 = t2; s3 = t3;
    }
    uint8_t *p = out;
    p[0]  = sbox[s0 >> 24]; p[1]  = sbox[(s1 >> 16) & 0xFF];
    p[2]  = sbox[(s2 >> 8) & 0xFF]; p[3]  = sbox[s3 & 0xFF];
    p[4]  = sbox[s1 >> 24]; p[5]  = sbox[(s2 >> 16) & 0xFF];
    p[6]  = sbox[(s3 >> 8) & 0xFF]; p[7]  = sbox[s0 & 0xFF];
    p[8]  = sbox[s2 >> 24]; p[9]  = sbox[(s3 >> 16) & 0xFF];
    p[10] = sbox[(s0 >> 8) & 0xFF]; p[11] = sbox[s1 & 0xFF];
    p[12] = sbox[s3 >> 24]; p[13] = sbox[(s0 >> 16) & 0xFF];
    p[14] = sbox[(s1 >> 8) & 0xFF]; p[15] = sbox[s2 & 0xFF];
    for (int i = 0; i < 4; i++) {
        uint32_t w = rk[40 + i];
        out[4*i+0] ^= (w >> 24) & 0xFF;
        out[4*i+1] ^= (w >> 16) & 0xFF;
        out[4*i+2] ^= (w >>  8) & 0xFF;
        out[4*i+3] ^= w & 0xFF;
    }
}

/* ========== 解密（标量标准流程，复用加密轮密钥）========== */
static void aes_ttable_decrypt(const uint8_t *in, uint8_t *out, const void *ctx) {
    const aes_ttable_ctx *c = (const aes_ttable_ctx*)ctx;
    const uint32_t *rk = c->rk_enc;
    uint8_t state[16];
    memcpy(state, in, 16);
    AddRoundKey(state, rk + 40);
    for (int r = 9; r >= 1; r--) {
        InvShiftRows(state);
        InvSubBytes(state);
        AddRoundKey(state, rk + 4 * r);
        InvMixColumns(state);
    }
    InvShiftRows(state);
    InvSubBytes(state);
    AddRoundKey(state, rk);
    memcpy(out, state, 16);
}

const block_cipher_t aes_ttable_impl = {
    .name = "AES-Ttable",
    .ctx_size = sizeof(aes_ttable_ctx),
    .block_size = 16,
    .key_schedule = aes_ttable_key_schedule,
    .encrypt = aes_ttable_encrypt,
    .decrypt = aes_ttable_decrypt
};
