/* 标量 xtime 与 mul */
static uint8_t xtime(uint8_t a) { return (a<<1) ^ ((a&0x80)?0x1b:0); }
static uint8_t mul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    while (b) { if (b & 1) r ^= a; a = xtime(a); b >>= 1; }
    return r;
}

/* 标量 MixColumns / InvMixColumns */
static void MixColumns(uint8_t state[16]) {
    for (int c = 0; c < 4; c++) {
        int idx = 4 * c;
        uint8_t a0 = state[idx+0], a1 = state[idx+1], a2 = state[idx+2], a3 = state[idx+3];
        state[idx+0] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
        state[idx+1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
        state[idx+2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
        state[idx+3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
    }
}
static void InvMixColumns(uint8_t state[16]) {
    for (int c = 0; c < 4; c++) {
        int idx = 4 * c;
        uint8_t a0 = state[idx+0], a1 = state[idx+1], a2 = state[idx+2], a3 = state[idx+3];
        state[idx+0] = mul(0x0e, a0) ^ mul(0x0b, a1) ^ mul(0x0d, a2) ^ mul(0x09, a3);
        state[idx+1] = mul(0x09, a0) ^ mul(0x0e, a1) ^ mul(0x0b, a2) ^ mul(0x0d, a3);
        state[idx+2] = mul(0x0d, a0) ^ mul(0x09, a1) ^ mul(0x0e, a2) ^ mul(0x0b, a3);
        state[idx+3] = mul(0x0b, a0) ^ mul(0x0d, a1) ^ mul(0x09, a2) ^ mul(0x0e, a3);
    }
}

