/* 上下文（只保留加密轮密钥） */
typedef struct {
    uint32_t rk_enc[44];   // 加密轮密钥
    __m128i rk_enc_simd[11]; // 可选，但解密不用 SIMD，直接复用标量解密
} aes_shuffle_ctx;

static const uint32_t Rcon[10] = {
    0x01000000, 0x02000000, 0x04000000, 0x08000000,
    0x10000000, 0x20000000, 0x40000000, 0x80000000,
    0x1b000000, 0x36000000
};

static void key_schedule(const uint8_t *key, void *ctx) {
    aes_shuffle_ctx *c = (aes_shuffle_ctx*)ctx;
    uint32_t *w = c->rk_enc;
    for (int i = 0; i < 4; i++) w[i] = GETU32(key + 4*i);
    for (int i = 4; i < 44; i++) {
        uint32_t t = w[i-1];
        if (i % 4 == 0) {
            t = (sbox[(t >> 16) & 0xFF] << 24) |
                (sbox[(t >>  8) & 0xFF] << 16) |
                (sbox[ t        & 0xFF] <<  8) |
                (sbox[ t >> 24 ]);
            t ^= Rcon[i/4 - 1];
        }
        w[i] = w[i-4] ^ t;
    }
    // 同时填充 SIMD 轮密钥（加密用）
    for (int i = 0; i < 11; i++) {
        uint8_t tmp[16];
        for (int j = 0; j < 4; j++) PUTU32(tmp + 4*j, w[4*i+j]);
        c->rk_enc_simd[i] = _mm_loadu_si128((__m128i*)tmp);
    }
}

/* 标量 SubBytes */
static void sub_bytes_scalar(uint8_t state[16]) {
    for (int i = 0; i < 16; i++) state[i] = sbox[state[i]];
}
static void inv_sub_bytes_scalar(uint8_t state[16]) {
    for (int i = 0; i < 16; i++) state[i] = inv_sbox[state[i]];
}
/* 标量 AddRoundKey */
static void AddRoundKey(uint8_t state[16], const uint32_t *rk) {
    for (int col = 0; col < 4; col++) {
        uint32_t w = rk[col];
        state[4*col+0] ^= (w >> 24) & 0xFF;
        state[4*col+1] ^= (w >> 16) & 0xFF;
        state[4*col+2] ^= (w >>  8) & 0xFF;
        state[4*col+3] ^= w & 0xFF;
    }
}

/* ========== 加密（shuffle 用于 ShiftRows）========== */
static void encrypt(const uint8_t *in, uint8_t *out, const void *ctx) {
    const aes_shuffle_ctx *c = (const aes_shuffle_ctx*)ctx;
    __m128i s = _mm_loadu_si128((__m128i*)in);
    s = _mm_xor_si128(s, c->rk_enc_simd[0]);
    __m128i sr_mask = _mm_loadu_si128((const __m128i*)sr_mask_bytes);

    for (int r = 1; r < 10; r++) {
        uint8_t buf[16];
        _mm_storeu_si128((__m128i*)buf, s);
        sub_bytes_scalar(buf);
        s = _mm_loadu_si128((__m128i*)buf);
        s = _mm_shuffle_epi8(s, sr_mask);
        _mm_storeu_si128((__m128i*)buf, s);
        MixColumns(buf);
        s = _mm_loadu_si128((__m128i*)buf);
        s = _mm_xor_si128(s, c->rk_enc_simd[r]);
    }
    uint8_t buf[16];
    _mm_storeu_si128((__m128i*)buf, s);
    sub_bytes_scalar(buf);
    s = _mm_loadu_si128((__m128i*)buf);
    s = _mm_shuffle_epi8(s, sr_mask);
    s = _mm_xor_si128(s, c->rk_enc_simd[10]);
    _mm_storeu_si128((__m128i*)out, s);
}

/* ========== 解密（标量标准流程，复用加密轮密钥）========== */
static void InvShiftRows(uint8_t state[16]) {
    uint8_t tmp[16];
    tmp[0] = state[0];  tmp[1] = state[13]; tmp[2] = state[10]; tmp[3] = state[7];
    tmp[4] = state[4];  tmp[5] = state[1];  tmp[6] = state[14]; tmp[7] = state[11];
    tmp[8] = state[8];  tmp[9] = state[5];  tmp[10]= state[2];  tmp[11]= state[15];
    tmp[12]= state[12]; tmp[13]= state[9];  tmp[14]= state[6];  tmp[15]= state[3];
    memcpy(state, tmp, 16);
}

static void decrypt(const uint8_t *in, uint8_t *out, const void *ctx) {
    const aes_shuffle_ctx *c = (const aes_shuffle_ctx*)ctx;
    const uint32_t *rk = c->rk_enc;
    uint8_t state[16];
    memcpy(state, in, 16);
    AddRoundKey(state, rk + 40);
    for (int r = 9; r >= 1; r--) {
        InvShiftRows(state);
        inv_sub_bytes_scalar(state);
        AddRoundKey(state, rk + 4 * r);
        InvMixColumns(state);
    }
    InvShiftRows(state);
    inv_sub_bytes_scalar(state);
    AddRoundKey(state, rk);
    memcpy(out, state, 16);
}

const block_cipher_t aes_shuffle_impl = {
    .name = "AES-shuffle",
    .ctx_size = sizeof(aes_shuffle_ctx),
    .block_size = 16,
    .key_schedule = key_schedule,
    .encrypt = encrypt,
    .decrypt = decrypt
};
